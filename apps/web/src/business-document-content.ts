const escapeHtml = (value: string): string =>
  value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

const sectionHtml = (section: TemplateSection): string => {
  const paragraphs = (section.paragraphs ?? [])
    .map((item) => `<p>${escapeHtml(item)}</p>`)
    .join('');
  const items = section.items?.length
    ? `<ol>${section.items.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ol>`
    : '';
  return `<h2>${escapeHtml(section.title)}</h2>${paragraphs}${items}`;
};

export const buildBusinessDocumentTemplateHtml = (
  file: string,
  templateName: string,
  description: string,
  prefill: string,
  today: string,
): string => {
  const blueprint = blueprints[file.slice(0, 2)] ?? additional[file.slice(0, 2)];
  if (!blueprint) throw new Error(`未配置在线正文模板：${templateName}`);
  const prefilled = prefill.trim()
    ? `<h2>关联业务信息</h2>${prefill
        .split('\n')
        .map((line) => `<p>${escapeHtml(line)}</p>`)
        .join('')}`
    : '';
  return [
    `<h2>${escapeHtml(templateName)}</h2>`,
    `<p><strong>文件用途：</strong>${escapeHtml(blueprint.purpose || description)}</p>`,
    `<p><strong>编制日期：</strong>${escapeHtml(today)}；<strong>文件状态：</strong>草稿；<strong>版本：</strong>V1</p>`,
    prefilled,
    '<h2>基本信息</h2>',
    `<ul>${blueprint.fields.map((field) => `<li>${escapeHtml(field)}</li>`).join('')}</ul>`,
    ...blueprint.sections.map(sectionHtml),
    '<h2>审批与确认</h2>',
    `<ul>${blueprint.approval.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ul>`,
    '<h2>版本与附件</h2>',
    '<ul><li>本版修改说明：从受控模板创建，首次填写。</li><li>附件清单及编号：〔填写检测报告、照片、图纸、封样、审批或业务单据编号〕。</li><li>保存为新版本后，历史版本不得覆盖；批准锁版前须完成正文、附件和审批信息复核。</li></ul>',
  ].join('');
};

export const isLegacyBusinessDocumentOutline = (value: string): boolean => {
  const normalized = value.replace(/\s+/gu, ' ').trim();
  return (
    normalized.length < 500 &&
    normalized.includes('一、基本信息') &&
    normalized.includes('二、业务内容') &&
    normalized.includes('三、技术与质量要求') &&
    normalized.includes('四、价格、交期或执行安排') &&
    normalized.includes('五、审批与确认')
  );
};
